// Builds what the Deploy to Cloudflare button deploys from apps/install, all committed: the Worker bundle
// (dist/worker.js) and the onboarding page's script, styles and fonts (public/assets, public/fonts). The button
// runs plain `npm install` and `wrangler deploy` on the folder, so nothing is built there.
// Deterministic: same sources, same bytes. `pnpm check:install-fresh` fails when a committed file is stale.
import { execFile } from "node:child_process";
import { copyFileSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";
import { build } from "esbuild";

const repo = fileURLToPath(new URL("../", import.meta.url));
const root = `${repo}apps/install/`;

await build({
  absWorkingDir: root,
  entryPoints: ["src/worker.ts"],
  outfile: "dist/worker.js",
  tsconfig: "tsconfig.json",
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2023",
  conditions: ["workerd", "worker", "browser"],
  mainFields: ["browser", "module", "main"],
  external: ["cloudflare:*", "node:*"],
  minify: true,
  legalComments: "none",
  charset: "utf8",
  banner: { js: "// Generated by `pnpm build:install` from apps/install/src. Do not edit." },
  logLevel: "warning",
});

rmSync(`${root}public/assets`, { recursive: true, force: true });
mkdirSync(`${root}public/assets`, { recursive: true });
await build({
  absWorkingDir: root,
  entryPoints: ["src/ui/main.tsx"],
  outfile: "public/assets/app.js",
  tsconfig: "src/ui/tsconfig.json",
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  jsx: "automatic",
  minify: true,
  define: { "process.env.NODE_ENV": '"production"' },
  legalComments: "none",
  charset: "utf8",
  logLevel: "warning",
});

const { stdout } = await promisify(execFile)(
  `${repo}node_modules/.bin/tailwindcss`,
  ["--input", "src/ui/styles.css", "--minify"],
  { cwd: root, maxBuffer: 16 * 1024 * 1024 },
);
writeFileSync(`${root}public/assets/app.css`, stdout);

// The admin's typefaces, self-hosted: the same files the lander catalog ships.
const fonts = `${repo}apps/sites/public/catalog/fonts/`;
rmSync(`${root}public/fonts`, { recursive: true, force: true });
mkdirSync(`${root}public/fonts`, { recursive: true });
for (const [from, to] of [
  ["archivo-latin.e19a759cff0c.woff2", "archivo-latin.woff2"],
  ["newsreader-latin.b2905872e9ec.woff2", "newsreader-latin.woff2"],
  ["OFL-archivo.txt", "OFL-archivo.txt"],
  ["OFL-newsreader.txt", "OFL-newsreader.txt"],
] as const) {
  copyFileSync(`${fonts}${from}`, `${root}public/fonts/${to}`);
}
