// Bundles packages/bootstrap into apps/install/worker.js, the file the Deploy button deploys.
// `--check` rebuilds in memory and fails if the committed file differs, so CI catches a stale bundle.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { build } from "esbuild";

const root = join(import.meta.dirname, "..");
const outfile = join(root, "apps/install/worker.js");
const banner = "// Generated by `pnpm install:build` from packages/bootstrap. Do not edit.";

const result = await build({
  entryPoints: [join(root, "packages/bootstrap/src/index.ts")],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2023",
  conditions: ["workerd", "worker", "browser"],
  mainFields: ["module", "main"],
  legalComments: "none",
  banner: { js: banner },
  write: false,
});
const code = result.outputFiles[0]?.text ?? "";

if (process.argv.includes("--check")) {
  let committed = "";
  try {
    committed = readFileSync(outfile, "utf8");
  } catch {}
  if (committed !== code) {
    console.error("apps/install/worker.js is stale: run `pnpm install:build` and commit it.");
    process.exit(1);
  }
} else {
  writeFileSync(outfile, code);
  console.log(`wrote ${outfile} (${code.length} bytes)`);
}
