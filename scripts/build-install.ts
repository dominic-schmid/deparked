// Builds what the Deploy to Cloudflare button deploys from apps/install, all committed: the Worker bundle
// (dist/worker.js) and the onboarding page's script, styles and fonts (public/assets, public/fonts). The button
// runs plain `npm install` and `wrangler deploy` on the folder, so nothing is built there.
// Deterministic: same sources, same bytes. `pnpm check:install-fresh` fails when a committed file is stale.
import { execFile } from "node:child_process";
import { copyFileSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";
import { build } from "esbuild";

const repo = fileURLToPath(new URL("../", import.meta.url));
const root = `${repo}apps/install/`;

await build({
  absWorkingDir: root,
  entryPoints: ["src/worker.ts"],
  outfile: "dist/worker.js",
  tsconfig: "tsconfig.json",
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2023",
  conditions: ["workerd", "worker", "browser"],
  mainFields: ["browser", "module", "main"],
  external: ["cloudflare:*", "node:*"],
  minify: true,
  legalComments: "none",
  charset: "utf8",
  banner: { js: "// Generated by `pnpm build:install` from apps/install/src. Do not edit." },
  logLevel: "warning",
});

rmSync(`${root}public/assets`, { recursive: true, force: true });
mkdirSync(`${root}public/assets`, { recursive: true });
const page = await build({
  absWorkingDir: root,
  entryPoints: ["src/ui/main.tsx"],
  outfile: "public/assets/app.js",
  tsconfig: "src/ui/tsconfig.json",
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  jsx: "automatic",
  // Arc's components are CSS Modules: their styles come out beside the script, and are joined to the Tailwind output below.
  loader: { ".module.css": "local-css" },
  minify: true,
  define: { "process.env.NODE_ENV": '"production"' },
  legalComments: "none",
  charset: "utf8",
  logLevel: "warning",
  write: false,
});
let arcStyles = "";
for (const file of page.outputFiles) {
  if (file.path.endsWith(".css")) arcStyles = file.text;
  else writeFileSync(file.path, file.contents);
}

const { stdout } = await promisify(execFile)(
  `${repo}node_modules/.bin/tailwindcss`,
  ["--input", "src/ui/styles.css", "--minify"],
  { cwd: root, maxBuffer: 16 * 1024 * 1024 },
);
// Arc's styles sit in Tailwind's `components` layer, so a utility class on an Arc component still overrides it.
// The layer order is restated because the first stylesheet to name the layers decides it.
writeFileSync(
  `${root}public/assets/app.css`,
  `${stdout}\n@layer theme,base,components,utilities;@layer components{${arcStyles}}\n`,
);

// The admin's typefaces, self-hosted (built by `pnpm --filter @deparked/ui fonts`). The admin's stylesheet reads them here.
const fonts = `${repo}packages/ui/fonts/`;
rmSync(`${root}public/fonts`, { recursive: true, force: true });
mkdirSync(`${root}public/fonts`, { recursive: true });
for (const name of [
  "bricolage-grotesque-latin.woff2",
  "instrument-sans-latin.woff2",
  "OFL-bricolagegrotesque.txt",
  "OFL-instrumentsans.txt",
] as const) {
  copyFileSync(`${fonts}${name}`, `${root}public/fonts/${name}`);
}
