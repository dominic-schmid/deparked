// Bundles apps/install/src into the one committed file the Deploy to Cloudflare button deploys.
// Deterministic: same sources, same bytes. `pnpm check:install-fresh` fails when the committed file is stale.
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = fileURLToPath(new URL("../apps/install/", import.meta.url));

await build({
  absWorkingDir: root,
  entryPoints: ["src/worker.ts"],
  outfile: "dist/worker.js",
  tsconfig: "tsconfig.json",
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2023",
  conditions: ["workerd", "worker", "browser"],
  mainFields: ["browser", "module", "main"],
  external: ["cloudflare:*", "node:*"],
  minify: true,
  legalComments: "none",
  charset: "utf8",
  banner: { js: "// Generated by `pnpm build:install` from apps/install/src. Do not edit." },
  logLevel: "warning",
});
