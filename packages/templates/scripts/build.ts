// Builds what the renderer cannot make at runtime (Tailwind and esbuild do not run in a Worker):
//   - each variant's Tailwind CSS, purged to that variant's markup, as src/**/styles.generated.ts
//   - each variant's island bundle, as /catalog/islands/<variant>.<hash>.js, listed in catalog.json
// Deterministic and committed. `pnpm check:templates-fresh` fails when a committed output is stale.
import { execFile } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync } from "node:fs";
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";
import { build } from "esbuild";
import type { Catalog } from "../src/catalog.ts";
import { CATALOG_DIR, updateCatalog } from "./catalog-file.ts";
import { GRADIENTS } from "./gradients.ts";

const root = fileURLToPath(new URL("../", import.meta.url));
const tailwind = `${root}node_modules/.bin/tailwindcss`;
const variants = (await readdir(`${root}src/variants`, { withFileTypes: true }))
  // `shared/` holds pieces the variants import, not a variant
  .filter((entry) => entry.isDirectory() && entry.name !== "shared")
  .map((entry) => entry.name)
  .sort();

async function compileCss(dir: string): Promise<void> {
  const { stdout } = await promisify(execFile)(tailwind, ["--input", `${dir}/styles.css`, "--minify"], { cwd: root });
  const banner = "// Generated by `pnpm build:templates` from styles.css and this folder's markup. Do not edit.";
  await writeFile(`${dir}/styles.generated.ts`, `${banner}\nexport const css = ${JSON.stringify(stdout.trim())};\n`);
}

await compileCss(`${root}src/placeholder`);
for (const variant of variants) await compileCss(`${root}src/variants/${variant}`);

const islandsDir = `${CATALOG_DIR}islands/`;
await rm(islandsDir, { recursive: true, force: true });
await mkdir(islandsDir, { recursive: true });
const islands: Catalog["islands"] = {};
for (const variant of variants) {
  const entry = `src/variants/${variant}/client.ts`;
  if (!existsSync(`${root}${entry}`)) continue;
  const result = await build({
    absWorkingDir: root,
    entryPoints: [entry],
    write: false,
    bundle: true,
    format: "esm",
    platform: "browser",
    target: "es2022",
    minify: true,
    jsx: "automatic",
    define: { "process.env.NODE_ENV": '"production"' },
    legalComments: "none",
    charset: "utf8",
    logLevel: "warning",
  });
  const bytes = result.outputFiles[0]?.contents;
  if (!bytes) throw new Error(`${entry}: no output`);
  const hash = createHash("sha256").update(bytes).digest("hex").slice(0, 12);
  const name = `${variant}.${hash}.js`;
  await writeFile(`${islandsDir}${name}`, bytes);
  islands[variant as keyof Catalog["islands"]] = { path: `/catalog/islands/${name}`, hash, bytes: bytes.length };
}
await updateCatalog({ gradients: GRADIENTS, islands });
