// Embeds migrations/*.sql into src/migrations.gen.ts, so a Worker and the installer can apply them without
// reading files. Run with `pnpm --filter @deparked/db embed-migrations`; a test fails when the output is stale.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const directory = join(root, "migrations");

function templateLiteral(text: string): string {
  return `\`${text.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${")}\``;
}

const entries = readdirSync(directory)
  .filter((name) => name.endsWith(".sql"))
  .sort()
  .map(
    (name) =>
      `  {\n    name: ${JSON.stringify(name)},\n    sql: ${templateLiteral(readFileSync(join(directory, name), "utf8"))},\n  },\n`,
  );

writeFileSync(
  join(root, "src/migrations.gen.ts"),
  `// Generated by scripts/embed-migrations.ts from migrations/*.sql. Do not edit.\nexport const migrationFiles: readonly { name: string; sql: string }[] = [\n${entries.join("")}];\n`,
);
